    [H, Ex, Ey] = probe(o, xp, yp, k0, Z0);
    hinc = exp(1i*o.kb*xp);                       % unit incident wave (thetai = 0)
    ratioH = abs(H)./abs(hinc);                   % |Hz|/|Hz_inc|  (= |Hz|, since |hinc| = 1)
    ratioE = hypot(abs(Ex), abs(Ey))/Z0;          % |E|/|E_inc|, with |E_inc| = Z0*H0


    plot(tidy3d(:,1),tidy3d(:,2),'o', phis*180/pi, ratioH, tidy3d(:,1),tidy3d(:,3),'o', phis*180/pi, ratioE, '--'); grid on; xlim([0 360]);
    xlabel('\theta (degrees)'); ylabel('Field ratios at r = 300 nm');
    legend('|H_z|/|H_z^{inc}| (Tidy3D)','|H_z|/|H_z^{inc}| (SIM)', '|E|/|E^{inc}| (Tidy3D)', '|E|/|E^{inc}| (SIM)', 'Location', 'NorthEast');
    print -dpng figure6_tidy3d_vs_sim
end


function [H, Ex, Ey] = probe(o, X, Y, k0, Z0)
% total Hz and E at points outside the object from the sim2d boundary solution
%   Hs(r) = sum over boundary of [U dG/dn' - G dU/dn'] ds'   (trapezoidal rule)
kb = o.kb;  w = (2*pi/o.N)*o.Ja;  r = o.r;  n = o.nrm;  U = o.U;  psi = o.dUn;
H = zeros(size(X));  Hx = H;  Hy = H;
for i = 1:numel(X)
    Rx = X(i) - r(1,:);  Ry = Y(i) - r(2,:);  R = hypot(Rx, Ry);
    H0 = besselh(0,1,kb*R);  H1 = besselh(1,1,kb*R);
    G   = 0.25i*H0;
    RnR = -(Rx.*n(1,:) + Ry.*n(2,:))./R;          % (r'-r).n'/R
    dGn = -0.25i*kb*H1.*RnR;                      % dG/dn'
    gGx = -0.25i*kb*H1.*Rx./R;   gGy = -0.25i*kb*H1.*Ry./R;     % grad_r G
    fac = (kb*H0 - 2*H1./R)./R;
    gDx = -0.25i*kb*(-n(1,:).*H1./R + RnR.*R.*fac.*Rx./R);      % grad_r dG/dn'
    gDy = -0.25i*kb*(-n(2,:).*H1./R + RnR.*R.*fac.*Ry./R);
    hi  = exp(1i*kb*X(i));                                      % incident Hz
    H(i)  = hi + sum((U.*dGn - G.*psi).*w);
    Hx(i) = 1i*kb*hi + sum((U.*gDx - gGx.*psi).*w);
    Hy(i) = sum((U.*gDy - gGy.*psi).*w);
end
Ex =  1i*Z0/(k0*o.epsb)*Hy;          % E = (i Z0/(k0 eps)) grad(Hz) x z
Ey = -1i*Z0/(k0*o.epsb)*Hx;
end